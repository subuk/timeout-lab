"""Generate browser wire types from Go JSON structs; Go remains the schema owner."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source='\n'.join(p.read_text() for p in (root/'core').glob('*.go') if not p.name.endswith('_test.go'))
structs=dict(re.findall(r'type (\w+) struct \{\n(.*?)\n\}',source,re.S))
aliases=dict(re.findall(r'^type (\w+) (map\[string\]\w+)$',source,re.M))
needed=set()
def convert(t):
    t=t.lstrip('*')
    if t.startswith('[]'): return convert(t[2:])+'[]'
    if t.startswith('map[string]'): return 'Record<string, '+convert(t[11:])+'>'
    if t in ('float64','int','uint64'): return 'number'
    if t=='bool': return 'boolean'
    if t=='string': return 'string'
    needed.add(t)
    return t
out=['// Generated by scripts/generate-types.py. Do not edit manually.']
needed.update(['Snapshot', 'RequestOptions'])
while needed:
    name=sorted(needed)[0]; needed.remove(name)
    if any(line.startswith('export interface '+name+' ') or line.startswith('export type '+name+' ') for line in out): continue
    if name in aliases:
        out.append('export type '+name+' = '+convert(aliases[name])+';');continue
    fields=[]; parents=[]
    for line in structs[name].splitlines():
        match=re.search(r'^\s*\w+\s+(\S+)\s+`json:"([^",]+)(,omitempty)?"`',line)
        if match:
            typ,key,optional=match.groups();fields.append(f'  {key}{"?" if optional else ""}: {convert(typ)};')
        elif re.match(r'^\s+[A-Z]\w+\s*$',line): parents.append(convert(line.strip()))
    out.append('export interface '+name+(' extends '+', '.join(parents) if parents else '')+' {\n'+'\n'.join(fields)+'\n}')
(root/'src/model.ts').write_text('\n\n'.join(out)+'\n')
